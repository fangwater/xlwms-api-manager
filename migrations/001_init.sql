CREATE TABLE IF NOT EXISTS xlwms_warehouses (
    wh_code text PRIMARY KEY,
    warehouse_name text,
    api_base_url text NOT NULL,
    app_key_ciphertext text NOT NULL,
    app_secret_ciphertext text NOT NULL,
    app_key_hint text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    disabled_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_xlwms_warehouses_active
    ON xlwms_warehouses (wh_code) WHERE is_active;

