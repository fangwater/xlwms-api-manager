CREATE TABLE IF NOT EXISTS xlwms_cost_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wh_code text NOT NULL,
    cost_no text NOT NULL,
    item_index integer NOT NULL,
    bill_item_name text,
    bill_item_total numeric,
